"""
report_generator.py — Research report builder.

Generates structured PDF and Markdown reports from a research session,
using IBM Granite to write narrative sections.
"""

from __future__ import annotations

import logging
from datetime import datetime
from pathlib import Path
from typing import TYPE_CHECKING

from .granite_client import GraniteClient

if TYPE_CHECKING:
    from .literature_search import Paper
    from .references import ReferenceManager

logger = logging.getLogger("research_agent.report")


class ReportGenerator:
    """
    Composes a full research report (Markdown + optional PDF) covering:
      - Executive Summary
      - Literature Overview
      - Key Themes & Gaps
      - Proposed Hypotheses
      - References
    """

    def __init__(self, client: GraniteClient) -> None:
        self._client = client

    # ── Markdown report ──────────────────────────────────────────────────────

    def generate_markdown(
        self,
        research_question: str,
        papers: "list[Paper]",
        synthesis: str,
        hypotheses: str,
        ref_manager: "ReferenceManager",
        output_path: Path | None = None,
    ) -> str:
        """
        Build a complete Markdown research report.

        Returns
        -------
        str
            Markdown text (also written to output_path if provided).
        """
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M")

        # Executive summary via Granite
        exec_summary = self._client.generate(
            f"Write a concise executive summary (3–4 sentences) for a research report "
            f"on the following question: '{research_question}'. "
            f"Mention that {len(papers)} relevant papers were identified.\n\nSummary:"
        )

        # Key themes via Granite
        theme_context = "\n".join(f"- {p.title} ({p.year or 'n.d.'})" for p in papers[:10])
        key_themes = self._client.generate(
            f"Based on these paper titles, identify 3–5 key research themes as bullet points:\n"
            f"{theme_context}\n\nKey themes:"
        )

        # Build Markdown
        lines = [
            f"# Research Report",
            f"",
            f"**Research Question:** {research_question}",
            f"**Generated:** {timestamp}  ",
            f"**Papers Retrieved:** {len(papers)}  ",
            f"**Powered by:** IBM Granite on IBM Cloud",
            f"",
            f"---",
            f"",
            f"## Executive Summary",
            f"",
            exec_summary,
            f"",
            f"---",
            f"",
            f"## Papers Found",
            f"",
        ]

        for i, paper in enumerate(papers, 1):
            authors = ", ".join(paper.authors[:3])
            if len(paper.authors) > 3:
                authors += " et al."
            lines += [
                f"### {i}. {paper.title}",
                f"",
                f"- **Authors:** {authors or 'N/A'}",
                f"- **Year:** {paper.year or 'N/A'}",
                f"- **Source:** {paper.source}",
                f"- **Citations:** {paper.citation_count}",
                f"- **URL:** {paper.url}",
                f"",
                f"**Abstract:** {(paper.abstract or 'N/A')[:500]}{'…' if len(paper.abstract or '') > 500 else ''}",
                f"",
            ]

        lines += [
            f"---",
            f"",
            f"## Key Research Themes",
            f"",
            key_themes,
            f"",
            f"---",
            f"",
            f"## Literature Synthesis",
            f"",
            synthesis,
            f"",
            f"---",
            f"",
            f"## Proposed Hypotheses",
            f"",
            hypotheses,
            f"",
            f"---",
            f"",
            f"## References",
            f"",
            f"```bibtex",
            ref_manager.export_bibtex(),
            f"```",
            f"",
            f"---",
            f"*Generated by Research Agent using IBM Granite on IBM watsonx.ai*",
        ]

        md = "\n".join(lines)

        if output_path:
            output_path.parent.mkdir(parents=True, exist_ok=True)
            output_path.write_text(md, encoding="utf-8")
            logger.info("Markdown report written to %s", output_path)

        return md

    # ── PDF report (optional) ────────────────────────────────────────────────

    def generate_pdf(self, markdown_text: str, output_path: Path) -> bool:
        """
        Convert Markdown report to PDF using reportlab.
        Returns True on success, False if reportlab is unavailable.
        """
        try:
            from reportlab.lib.pagesizes import A4
            from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
            from reportlab.lib.units import cm
            from reportlab.platypus import (
                SimpleDocTemplate, Paragraph, Spacer, HRFlowable
            )
            from reportlab.lib import colors
        except ImportError:
            logger.warning("reportlab not installed — PDF generation skipped.")
            return False

        output_path.parent.mkdir(parents=True, exist_ok=True)
        doc = SimpleDocTemplate(
            str(output_path),
            pagesize=A4,
            leftMargin=2.5 * cm,
            rightMargin=2.5 * cm,
            topMargin=2.5 * cm,
            bottomMargin=2.5 * cm,
        )

        styles = getSampleStyleSheet()
        story = []

        for line in markdown_text.splitlines():
            stripped = line.strip()
            if stripped.startswith("# ") and not stripped.startswith("## "):
                story.append(Paragraph(stripped[2:], styles["Title"]))
                story.append(Spacer(1, 0.4 * cm))
            elif stripped.startswith("## "):
                story.append(Spacer(1, 0.3 * cm))
                story.append(Paragraph(stripped[3:], styles["Heading2"]))
            elif stripped.startswith("### "):
                story.append(Paragraph(stripped[4:], styles["Heading3"]))
            elif stripped == "---":
                story.append(HRFlowable(width="100%", thickness=0.5, color=colors.grey))
                story.append(Spacer(1, 0.2 * cm))
            elif stripped:
                story.append(Paragraph(stripped, styles["Normal"]))
                story.append(Spacer(1, 0.15 * cm))

        doc.build(story)
        logger.info("PDF report written to %s", output_path)
        return True
